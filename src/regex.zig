//! Standalone regular-expression constraint (BLG_CONSTRAINT_REGEX,
//! ADR-0015): the whole generated text must match the pattern, ECMA-262
//! `^(?:p)$` over Unicode scalar values, with the syntax and character
//! classes of `pattern` (src/pattern.zig compiled in full-match mode).
//!
//! The session state is a DFA state plus the pending bytes of one UTF-8
//! sequence. A byte is legal only when the text so far can still be
//! completed to a match: a whole code point must lead to a DFA state from
//! which an accept state is reachable (`live`), a pending lead or
//! continuation byte must leave some completing code point that does. On
//! a byte-complete vocabulary every live state can be completed one byte
//! at a time, so the mask is exact without a completion search; other
//! vocabularies are refused at compile time.

const std = @import("std");
const pattern = @import("pattern.zig");
const tokenizer = @import("tokenizer.zig");
const work_mod = @import("work.zig");

pub const Program = struct {
    dfa: pattern.Dfa,
    /// live[s]: an accept state is reachable from DFA state s.
    live: []const bool,
    strip_lead_space: bool,
    a: std.mem.Allocator,

    pub fn deinit(self: *Program) void {
        self.a.free(self.live);
        self.dfa.deinit();
    }
};

pub const CompileError = error{ Invalid, Unsupported, Unsatisfiable, OutOfMemory };

/// Compiles the UTF-8 regex source `src`. On Unsupported, `err_offset`
/// holds the byte offset of the first byte of the unsupported construct,
/// or the source length when a size limit was hit; on Invalid, the offset
/// where parsing stopped.
pub fn compile(a: std.mem.Allocator, src: []const u8, strip_lead_space: bool, err_offset: *usize) CompileError!Program {
    err_offset.* = src.len;
    var dfa = pattern.compile(a, src, .{ .mode = .full, .error_offset = err_offset }) catch |e| switch (e) {
        error.Invalid => return error.Invalid,
        error.Unsupported => return error.Unsupported,
        error.OutOfMemory => return error.OutOfMemory,
    };
    errdefer dfa.deinit();
    const live = try liveStates(a, &dfa);
    errdefer a.free(live);
    if (!live[dfa.start()]) return error.Unsatisfiable;
    return .{ .dfa = dfa, .live = live, .strip_lead_space = strip_lead_space, .a = a };
}

/// Reverse breadth-first search from the accept states.
fn liveStates(a: std.mem.Allocator, dfa: *const pattern.Dfa) error{OutOfMemory}![]bool {
    const n = dfa.states.len;
    const live = try a.alloc(bool, n);
    errdefer a.free(live);
    @memset(live, false);
    const off = try a.alloc(u32, n + 1);
    defer a.free(off);
    @memset(off, 0);
    for (dfa.states) |st| {
        for (st.trans) |t| off[t.to + 1] += 1;
    }
    for (1..n + 1) |i| off[i] += off[i - 1];
    const preds = try a.alloc(u32, off[n]);
    defer a.free(preds);
    const fill = try a.alloc(u32, n);
    defer a.free(fill);
    @memcpy(fill, off[0..n]);
    for (dfa.states, 0..) |st, s| {
        for (st.trans) |t| {
            preds[fill[t.to]] = @intCast(s);
            fill[t.to] += 1;
        }
    }
    const queue = try a.alloc(u32, n);
    defer a.free(queue);
    var qlen: usize = 0;
    for (dfa.states, 0..) |st, s| {
        if (s != 0 and st.accept) {
            live[s] = true;
            queue[qlen] = @intCast(s);
            qlen += 1;
        }
    }
    var qi: usize = 0;
    while (qi < qlen) : (qi += 1) {
        const s = queue[qi];
        for (preds[off[s]..off[s + 1]]) |p| {
            if (p == 0 or live[p]) continue;
            live[p] = true;
            queue[qlen] = p;
            qlen += 1;
        }
    }
    return live;
}

pub const State = struct {
    d: pattern.RunState = 1,
    /// Bits of the code point read so far while `rem` continuation bytes
    /// are pending; the next one must lie in lo..hi.
    cp: u32 = 0,
    rem: u8 = 0,
    lo: u8 = 0x80,
    hi: u8 = 0xBF,
    /// A byte was fed (the dropped leading space of a strip-lead-space
    /// decoder counts).
    started: bool = false,
};

pub fn initial(p: *const Program) State {
    return .{ .d = p.dfa.start() };
}

pub fn canEnd(p: *const Program, st: State) bool {
    return st.rem == 0 and p.dfa.isAccept(st.d);
}

/// Feeds one byte; false when no completion of the text matches. `st` is
/// unspecified after false.
pub fn feedByte(p: *const Program, st: *State, b: u8) bool {
    if (!st.started) {
        st.started = true;
        // The decoder drops one leading space of the whole text: the
        // generated bytes are " " + t for any match t, or a match t that
        // does not start with a space.
        if (p.strip_lead_space and b == ' ') return true;
    }
    if (st.rem == 0) {
        switch (b) {
            0x00...0x7F => return step(p, st, b),
            0xC2...0xDF => lead(st, b & 0x1F, 1, 0x80, 0xBF),
            0xE0 => lead(st, b & 0x0F, 2, 0xA0, 0xBF),
            0xE1...0xEC, 0xEE...0xEF => lead(st, b & 0x0F, 2, 0x80, 0xBF),
            0xED => lead(st, b & 0x0F, 2, 0x80, 0x9F),
            0xF0 => lead(st, b & 0x07, 3, 0x90, 0xBF),
            0xF1...0xF3 => lead(st, b & 0x07, 3, 0x80, 0xBF),
            0xF4 => lead(st, b & 0x07, 3, 0x80, 0x8F),
            else => return false,
        }
        return pendingAlive(p, st);
    }
    if (b < st.lo or b > st.hi) return false;
    st.cp = (st.cp << 6) | (b & 0x3F);
    st.rem -= 1;
    st.lo = 0x80;
    st.hi = 0xBF;
    if (st.rem == 0) return step(p, st, @intCast(st.cp));
    return pendingAlive(p, st);
}

/// The state after `bytes`, or null when a byte is illegal.
pub fn feed(p: *const Program, st: State, bytes: []const u8) ?State {
    var s = st;
    for (bytes) |b| {
        if (!feedByte(p, &s, b)) return null;
    }
    return s;
}

fn lead(st: *State, bits: u8, rem: u8, lo: u8, hi: u8) void {
    st.cp = bits;
    st.rem = rem;
    st.lo = lo;
    st.hi = hi;
}

fn step(p: *const Program, st: *State, cp: u21) bool {
    const next = p.dfa.feed(st.d, cp);
    if (next == 0 or !p.live[next]) return false;
    st.d = next;
    st.cp = 0;
    return true;
}

/// Some code point the pending bytes can still complete to leads to a
/// live DFA state.
fn pendingAlive(p: *const Program, st: *const State) bool {
    const free_bits: u5 = @intCast(6 * (@as(u32, st.rem) - 1));
    const base = st.cp << (free_bits + 6);
    const lo_cp = base | (@as(u32, st.lo & 0x3F) << free_bits);
    const hi_cp = base | (@as(u32, st.hi & 0x3F) << free_bits) | ((@as(u32, 1) << free_bits) - 1);
    for (p.dfa.states[st.d].trans) |t| {
        if (t.hi < lo_cp or t.lo > hi_cp) continue;
        if (p.live[t.to]) return true;
    }
    return false;
}

fn setBit(out: []u32, id: usize) void {
    out[id / 32] |= @as(u32, 1) << @intCast(id % 32);
}

/// Mask of `st` over the vocabulary: every ordinary token whose bytes are
/// legal, EOS when the text matches as it stands; special tokens never.
/// Walks the vocabulary trie, so tokens sharing a prefix share its feed.
pub fn fillMask(p: *const Program, tok: *const tokenizer.Tokenizer, st: State, out: []u32, w: *work_mod.Work) error{ Cancelled, ResourceLimit, DeadEnd }!void {
    @memset(out, 0);
    try walk(p, tok, 0, st, out, w);
    if (canEnd(p, st)) {
        for (tok.is_eos, 0..) |e, id| {
            if (e) setBit(out, id);
        }
    }
    for (out) |word| {
        if (word != 0) return;
    }
    return error.DeadEnd;
}

fn walk(p: *const Program, tok: *const tokenizer.Tokenizer, node: u32, st: State, out: []u32, w: *work_mod.Work) error{ Cancelled, ResourceLimit }!void {
    const trie = &tok.trie;
    const base: usize = trie.node_edge_off[node];
    const n: usize = trie.node_edge_len[node];
    try w.charge(n);
    for (base..base + n) |e| {
        var s = st;
        if (!feedByte(p, &s, trie.edge_byte[e])) continue;
        const child = trie.edge_child[e];
        var id = trie.node_token[child];
        while (id != tokenizer.NO_TOKEN) : (id = tok.token_chain[id]) {
            if (!tok.is_eos[id] and !tok.is_special[id]) setBit(out, id);
        }
        try walk(p, tok, child, s, out, w);
    }
}

fn testProgram(src: []const u8, strip: bool) !Program {
    var off: usize = 0;
    return compile(std.testing.allocator, src, strip, &off);
}

fn accepts(p: *const Program, text: []const u8) bool {
    const st = feed(p, initial(p), text) orelse return false;
    return canEnd(p, st);
}

test "regex: full match over code points" {
    var p = try testProgram("a[0-9]{2}|\\u{e9}+", false);
    defer p.deinit();
    try std.testing.expect(accepts(&p, "a12"));
    try std.testing.expect(!accepts(&p, "a1"));
    try std.testing.expect(feed(&p, initial(&p), "a1x") == null);
    try std.testing.expect(accepts(&p, "\xc3\xa9\xc3\xa9"));
    // A lead byte whose code points cannot continue the match dies at once.
    try std.testing.expect(feed(&p, initial(&p), "\xc3\xa8") == null);
    try std.testing.expect(feed(&p, initial(&p), "\xc4") == null);
    try std.testing.expect(feed(&p, initial(&p), "\xc3") != null);
    try std.testing.expect(!accepts(&p, "\xc3"));
}

test "regex: states that cannot reach an accept state are refused" {
    var p = try testProgram("ab|a(?:c$d)", false);
    defer p.deinit();
    try std.testing.expect(feed(&p, initial(&p), "ac") == null);
    try std.testing.expect(accepts(&p, "ab"));
}

test "regex: ECMA classes, dot and line terminators" {
    var p = try testProgram("\\d\\s.", false);
    defer p.deinit();
    try std.testing.expect(accepts(&p, "1 x"));
    // U+0661 is not \d; U+FEFF is \s; `.` excludes U+2028 and \r.
    try std.testing.expect(feed(&p, initial(&p), "\xd9\xa1") == null);
    try std.testing.expect(accepts(&p, "1\xef\xbb\xbfx"));
    try std.testing.expect(!accepts(&p, "1 \r"));
    try std.testing.expect(!accepts(&p, "1 \xe2\x80\xa8"));
}

test "regex: surrogates and overlong forms are illegal bytes" {
    var p = try testProgram("[^]*", false);
    defer p.deinit();
    try std.testing.expect(feed(&p, initial(&p), "\xed\xa0") == null);
    try std.testing.expect(feed(&p, initial(&p), "\xc0") == null);
    try std.testing.expect(feed(&p, initial(&p), "\xe0\x80") == null);
    try std.testing.expect(feed(&p, initial(&p), "\xf4\x90") == null);
    try std.testing.expect(accepts(&p, "\xf4\x8f\xbf\xbf"));
}

test "regex: a strip-lead-space decoder drops one leading space" {
    var p = try testProgram("x+", true);
    defer p.deinit();
    try std.testing.expect(accepts(&p, " x"));
    try std.testing.expect(accepts(&p, "xx"));
    try std.testing.expect(feed(&p, initial(&p), "  ") == null);
    var q = try testProgram(" ?y", true);
    defer q.deinit();
    try std.testing.expect(accepts(&q, "  y"));
    try std.testing.expect(accepts(&q, " y"));
    try std.testing.expect(accepts(&q, "y"));
}

test "regex: unsupported constructs and empty languages" {
    var off: usize = 0;
    try std.testing.expectError(error.Unsupported, compile(std.testing.allocator, "a(?=b)", false, &off));
    try std.testing.expectEqual(@as(usize, 1), off); // the '(' of the lookahead
    try std.testing.expectError(error.Invalid, compile(std.testing.allocator, "a[", false, &off));
    try std.testing.expectError(error.Unsatisfiable, compile(std.testing.allocator, "[]", false, &off));
}
