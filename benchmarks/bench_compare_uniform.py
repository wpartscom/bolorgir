#!/usr/bin/env python3
"""Comparable benchmark under IDENTICAL load (SPEC 10.5).

All three engines (Bolorgir lazy/adaptive, XGrammar, llguidance):
- the same HF tokenizer (openai-community/gpt2 by default,
  revision pinned in manifest.json);
- the same schema from the corpus;
- the same token trace (a pre-set valid trace, SPEC 10.5):
  the trace is generated by the zig engine (canonical-v1 profile - the
  strictest, compact JSON), then coverage of every trace token is checked
  against XGrammar and llguidance masks. Common trace = accepted by all three.

Metrics (SPEC 10.4 B1/B2, 10.5): tokenizer prepare, cold compile (per
args.repeats fresh compilers; in the scored v3 protocol run - 1000), warm compile, first mask, fill_mask/accept p50/p95/p99/max
on the common trace (>= 10k observations), process peak RSS.

Run from the project root:
    PYTHONPATH=python:benchmarks python3 benchmarks/bench_compare_uniform.py \
        --schema closed_object_action_amount
"""

import argparse
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bench_common as bc

TOKENIZER_NAME = "openai-community/gpt2"
TOKENIZER_REVISION = "607a30d783dfa663caf39e06633721c8d4cfcd7e"


# ---------- common trace ----------
# Trace acceptance is checked by actual accept/consume (the truth about
# admissibility), NOT by the mask bit: in llguidance 1.8.0 inside forced
# literals the mask contains only the "greedy" spelling (e.g. after '{" only
# 'action', but 'act' is accepted by consume_token and continues with 'ion').
# The mask meanwhile is the stock production path, and its latency is what
# we measure.

def zig_gen_trace(zc, constraint, vocab_size, rng, max_steps=256):
    session = constraint.create_session()
    trace, completed = bc.gen_trace(session, vocab_size, rng, max_steps=max_steps)
    session.abort()
    return trace, completed


def zig_check_trace(constraint, trace):
    session = constraint.create_session()
    try:
        for t in trace:
            session.accept_token(t)
        return session.can_end()
    except Exception:
        return False
    finally:
        session.abort()


def xg_check_trace(xg, np, compiled, trace):
    m = xg.GrammarMatcher(compiled)
    for t in trace:
        if not m.accept_token(t):
            return False
    return True


def lg_check_trace(lg, tok, grm, trace):
    m = lg.LLMatcher(tok, grm)
    for t in trace:
        if m.is_error() or not m.consume_token(t):
            return False
    return not m.is_error()


# ---------- measurements ----------

def bench_zig(zc, hf_tok, schema, schema_bytes, trace, args, mode):
    vocab_size = None
    prepare_ns, cold_compile, first_mask = [], [], []
    for _ in range(args.repeats):
        t0 = bc.now_ns()
        bundle = zc.TokenizerBundle.from_hf(hf_tok, use_cache=False)
        t1 = bc.now_ns()
        engine = zc.Engine(mode=mode, memory_limit_mb=256, tokenizer=bundle)
        t2 = bc.now_ns()
        # Prepared immutable input (bytes) - the same input class as
        # the competitors' (a ready string): dumps is not part of the
        # measurement; dict-path cost is published separately.
        constraint = engine.compile(schema_bytes)
        t3 = bc.now_ns()
        session = constraint.create_session()
        session.fill_mask()
        t4 = bc.now_ns()
        prepare_ns.append(t1 - t0)
        cold_compile.append(t3 - t2)
        first_mask.append(t4 - t3)
        vocab_size = engine.vocab_size
        session.close()
        constraint.close()
        engine.close()

    bundle = zc.TokenizerBundle.from_hf(hf_tok)
    engine = zc.Engine(mode=mode, memory_limit_mb=256, tokenizer=bundle)
    constraint = engine.compile(schema_bytes)
    warm_compile = []
    for _ in range(max(args.repeats, args.min_warm_observations)):
        t0 = bc.now_ns()
        c = engine.compile(schema_bytes)
        warm_compile.append(bc.now_ns() - t0)
        c.close()
    warm_compile_dict = []
    for _ in range(max(args.repeats, args.min_warm_observations)):
        t0 = bc.now_ns()
        c = engine.compile(schema)
        warm_compile_dict.append(bc.now_ns() - t0)
        c.close()

    for _ in range(3):  # warmup (SPEC 10.1: warmup_iterations)
        session = constraint.create_session()
        for t in trace:
            session.fill_mask()
            session.accept_token(t)
        session.abort()
        session.close()
    mask_ns, accept_ns = [], []
    observations = 0
    while observations < args.min_observations:
        session = constraint.create_session()
        for t in trace:
            t0 = bc.now_ns()
            session.fill_mask()
            t1 = bc.now_ns()
            session.accept_token(t)
            t2 = bc.now_ns()
            mask_ns.append(t1 - t0)
            accept_ns.append(t2 - t1)
        observations += len(trace)
        session.abort()
        session.close()
    constraint.close()
    engine.close()

    return {
        "tokenizer_prepare_ns": bc.percentile_stats(prepare_ns),
        "cold_compile_ns": bc.percentile_stats(cold_compile),
        "warm_compile_ns": bc.percentile_stats(warm_compile),
        "warm_compile_dict_ns": bc.percentile_stats(warm_compile_dict),
        "first_mask_ns": bc.percentile_stats(first_mask),
        "fill_mask_ns": bc.percentile_stats(mask_ns),
        "accept_ns": bc.percentile_stats(accept_ns),
        "observations": len(mask_ns),
        "vocab_size": vocab_size,
        # Raw observations (SPEC 10.5): independent recomputation of
        # spread and thresholds without a rerun.
        "raw_ns": {
            "tokenizer_prepare_ns": prepare_ns,
            "cold_compile_ns": cold_compile,
            "warm_compile_ns": warm_compile,
            "warm_compile_dict_ns": warm_compile_dict,
            "first_mask_ns": first_mask,
            "fill_mask_ns": mask_ns,
            "accept_ns": accept_ns,
        },
    }


def bench_xgrammar(xg, np, hf_tok, schema_str, trace, args):
    prepare_ns, cold_compile, first_mask = [], [], []
    vocab_size = None
    for _ in range(args.repeats):
        t0 = bc.now_ns()
        info = xg.TokenizerInfo.from_huggingface(hf_tok)
        t1 = bc.now_ns()
        compiler = xg.GrammarCompiler(info, cache_enabled=False)
        t2 = bc.now_ns()
        compiled = compiler.compile_json_schema(schema_str)
        t3 = bc.now_ns()
        matcher = xg.GrammarMatcher(compiled)
        bitmask = xg.allocate_token_bitmask(1, info.vocab_size)
        matcher.fill_next_token_bitmask(bitmask)
        t4 = bc.now_ns()
        prepare_ns.append(t1 - t0)
        cold_compile.append(t3 - t2)
        first_mask.append(t4 - t3)
        vocab_size = info.vocab_size

    info = xg.TokenizerInfo.from_huggingface(hf_tok)
    compiler = xg.GrammarCompiler(info)
    warm_compile = []
    for _ in range(max(args.repeats, args.min_warm_observations)):
        t0 = bc.now_ns()
        compiler.compile_json_schema(schema_str)
        warm_compile.append(bc.now_ns() - t0)

    compiled = compiler.compile_json_schema(schema_str)
    bitmask = xg.allocate_token_bitmask(1, info.vocab_size)
    for _ in range(3):  # warmup
        m = xg.GrammarMatcher(compiled)
        for t in trace:
            m.fill_next_token_bitmask(bitmask)
            m.accept_token(t)
    mask_ns, accept_ns = [], []
    observations = 0
    while observations < args.min_observations:
        m = xg.GrammarMatcher(compiled)
        for t in trace:
            t0 = bc.now_ns()
            m.fill_next_token_bitmask(bitmask)
            t1 = bc.now_ns()
            m.accept_token(t)
            t2 = bc.now_ns()
            mask_ns.append(t1 - t0)
            accept_ns.append(t2 - t1)
        observations += len(trace)

    return {
        "tokenizer_prepare_ns": bc.percentile_stats(prepare_ns),
        "cold_compile_ns": bc.percentile_stats(cold_compile),
        "warm_compile_ns": bc.percentile_stats(warm_compile),
        "first_mask_ns": bc.percentile_stats(first_mask),
        "fill_mask_ns": bc.percentile_stats(mask_ns),
        "accept_ns": bc.percentile_stats(accept_ns),
        "observations": len(mask_ns),
        "vocab_size": vocab_size,
        "raw_ns": {
            "tokenizer_prepare_ns": prepare_ns,
            "cold_compile_ns": cold_compile,
            "warm_compile_ns": warm_compile,
            "first_mask_ns": first_mask,
            "fill_mask_ns": mask_ns,
            "accept_ns": accept_ns,
        },
    }


